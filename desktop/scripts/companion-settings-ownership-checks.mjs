import assert from 'node:assert/strict'

// Called only by the isolated synthetic-book smoke, with both models disabled.
export async function checkCompanionSettingsOwnership({ app, page, owner, capture, checks, errors }) {
  const appearance = page.locator('.library-preferences-dialog')
  if (await appearance.evaluate(node => node.open)) await page.getByRole('button', { name: '关闭外观设置' }).click()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  const voices = page.getByTestId('companion-sound-voice')
  const [libraryVoice] = await voices.selectOption({ index: 1 })
  await page.waitForFunction(async voice => (await window.companionSettings.get()).voice.voice === voice, libraryVoice)
  const careBefore = await page.evaluate(() => window.companionCare.get())
  await page.getByRole('button', { name: '关闭外观设置' }).click()
  await page.getByTestId('library-continue-writing').click()
  await page.getByTestId('external-companion').waitFor()
  await page.getByTestId('workspace-loading').waitFor({ state: 'detached' })
  assert.equal(app.windows().filter(w => /pet\.html/.test(w.url())).length, 0, 'entering work does not enable pet')
  await page.getByTestId('external-companion').click()
  let pet
  for (let i = 0; i < 100 && !pet; i++) {
    pet = app.windows().find(w => /pet\.html/.test(w.url()))
    if (!pet) await page.waitForTimeout(100)
  }
  assert.ok(pet, 'explicitly enabled pet window exists')
  pet.on('pageerror', error => errors.push(error.message))
  await pet.getByTestId('pet-window-menu-toggle').click()
  await pet.getByRole('button', { name: '完整设置 ↗' }).click()
  const settings = page.getByTestId('companion-settings')
  await settings.waitFor()
  assert.equal(await voices.inputValue(), libraryVoice, 'library voice follows into writing settings')
  const petSettings = page.getByTestId('desktop-pet-settings')
  await petSettings.getByTestId('pet-scale').selectOption('0.75')
  await page.waitForFunction(async () => (await window.desktopPet.get()).preferences.scale === 0.75)
  await petSettings.getByRole('button', { name: '养成与活动', exact: true }).click()
  await petSettings.getByRole('checkbox', { name: '开启轻养成', exact: true }).waitFor()
  await petSettings.getByRole('button', { name: '麦克风', exact: true }).click()
  await petSettings.getByRole('heading', { name: '麦克风输入' }).waitFor()
  await petSettings.getByRole('button', { name: '外观与位置', exact: true }).click()
  await petSettings.scrollIntoViewIfNeeded()
  await page.waitForTimeout(400)
  await capture('writing-companion.png')
  const [writingVoice] = await voices.selectOption({ index: 2 })
  await page.waitForFunction(async voice => (await window.companionSettings.get()).voice.voice === voice, writingVoice)
  assert.equal(await pet.evaluate(async () => (await window.companionSettings.get()).voice.voice), writingVoice, 'detached pet shares the same voice')
  await owner.evaluate(window => window.webContents.setZoomFactor(1.25))
  await settings.getByRole('heading', { name: '写作时的陪伴方式' }).scrollIntoViewIfNeeded()
  await page.waitForTimeout(500)
  assert.equal(await settings.getByRole('heading', { name: '写作时的陪伴方式' }).evaluate(node => {
    const bounds = node.getBoundingClientRect()
    return bounds.top >= 0 && bounds.bottom <= innerHeight
  }), true, 'capture includes the per-work presentation heading after scroll settles')
  await capture('writing-companion-options-125.png')
  assert.equal(await settings.evaluate(node => node.scrollWidth > node.clientWidth + 1), false)
  await page.getByRole('button', { name: '返回我的作品', exact: true }).click()
  await page.getByTestId('project-library').waitFor()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  assert.equal(await page.getByTestId('desktop-pet-settings').count(), 0)
  assert.equal(await voices.inputValue(), writingVoice, 'writing voice follows back to library')
  assert.equal(await page.getByTestId('companion-sound-volume').isDisabled(), true)
  assert.deepEqual(await page.evaluate(() => window.companionCare.get()), careBefore, 'changing settings does not reset the shared care archive')
  checks.push('library-writing-detached-shared-voice', 'pet-menu-opens-writing-settings', 'pet-controls-only-in-writing', 'pet-size-saved', 'care-and-microphone-reachable', 'care-archive-preserved', 'writing-options-fit-125-percent')
}
