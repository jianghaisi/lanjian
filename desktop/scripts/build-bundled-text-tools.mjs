// Offline, reproducible guest build. Upstream package scripts are never run.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const desktop = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = resolve(desktop, 'plugin-sources/text-tools')
const lock = JSON.parse(await readFile(resolve(sourceRoot, 'sources.json'), 'utf8'))
const check = process.argv.includes('--check'), sources = {}, notices = {}
for (const dependency of lock.dependencies) {
  const parts = [`${dependency.name} ${dependency.version}\n${dependency.repository.url}\nCommit: ${dependency.commit}\n`]
  for (const file of dependency.files) {
    const bytes = await readFile(resolve(sourceRoot, file.path))
    assert.equal(createHash('sha256').update(bytes).digest('hex'), file.sha256, `Changed upstream bytes: ${file.path}`)
    if (!file.path.endsWith('.js')) parts.push(`${file.upstreamPath}\n${bytes.toString('utf8')}`)
  }
  const entry = dependency.name === 'pangu' ? 'pangu-entry.js' : 'opencc-entry.js'
  const result = await build({ entryPoints: [resolve(sourceRoot, entry)], bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'es2022', charset: 'utf8', minify: true, legalComments: 'none', metafile: true })
  assert.equal(result.outputFiles.length, 1)
  assert.ok(Object.values(result.metafile.outputs).every(output => output.imports.length === 0), 'Guests cannot import modules')
  const source = `// Lanjian adaptation of ${dependency.name} ${dependency.version}: bundled, minified and wrapped as a preview-only plugin tool. See NOTICE.txt for upstream licenses.\n` + result.outputFiles[0].text
  assert.ok(Buffer.byteLength(source) <= 2 * 1024 * 1024, 'Guest entry exceeds package ceiling')
  sources[dependency.name] = source
  notices[dependency.name] = parts.join('\n\n')
}
const method = lock.methodology
notices.methodology = `Writing methodology adapted for Lanjian; original prompts and SDK integration.\n${method.repository}\nCommit: ${method.commit}\nReference: ${method.path}\n${method.licenseText}`
const generated = '// Generated by scripts/build-bundled-text-tools.mjs; do not edit.\n' +
  `export const textToolSources = ${JSON.stringify(sources, null, 2)} as const\n` +
  `export const writingPluginNotices = ${JSON.stringify(notices, null, 2)} as const\n`
const outputs = [
  ['src/main/modules/writing-plugins/domain/bundled-text-tools.generated.ts', generated],
  ['licenses/bundled-writing-plugins.txt', Object.values(notices).join('\n\n========================================\n\n') + '\n']
]
for (const [path, content] of outputs) {
  if (check) assert.equal(await readFile(resolve(desktop, path), 'utf8'), content, `Regenerate ${path}`)
  else await writeFile(resolve(desktop, path), content)
}
console.log(JSON.stringify({ checked: check, entries: Object.fromEntries(Object.entries(sources).map(([name, text]) => [name, Buffer.byteLength(text)])) }))
