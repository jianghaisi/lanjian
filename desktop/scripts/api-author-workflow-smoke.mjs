async function capture(name, width = 1440, height = 1000, zoom = 1, focus) {
  const owner = await app.browserWindow(page)
  await owner.evaluate((win, geometry) => { if (win.isMaximized()) win.unmaximize(); win.setContentSize(geometry.width, geometry.height); win.webContents.setZoomFactor(geometry.zoom) }, { width, height, zoom })
  await page.locator('.settings-editor').evaluate(e => { e.scrollTop = 0 })
  if (focus) await page.locator(focus).scrollIntoViewIfNeeded()
  await page.locator('.toast').waitFor({ state: 'hidden' })
  await page.waitForTimeout(450) // Allow the actual theme color transition to finish before capturing pixels.
  await page.evaluate(() => document.fonts.ready)
  await page.evaluate(() => new Promise(done => requestAnimationFrame(() => requestAnimationFrame(done))))
  const geometry = await manager().evaluate(e => ({ width: innerWidth, height: innerHeight, overflow: e.scrollWidth > e.clientWidth + 1, documentOverflow: document.documentElement.scrollWidth > innerWidth + 1 }))
  assert.equal(geometry.overflow, false); assert.equal(geometry.documentOverflow, false)
  const presentation = await page.evaluate(() => {
    const root = document.querySelector('.model-settings-page')
    const primary = document.querySelector('[data-testid="save-book-models"]') ?? document.querySelector('[data-testid="configure-book-models"]')
    return { background: getComputedStyle(root).backgroundImage, primary: primary ? getComputedStyle(primary).backgroundColor : null }
  })
  assert.match(presentation.background, /linear-gradient/)
  if (presentation.primary) assert.equal(presentation.primary, 'rgb(239, 163, 72)')
  geometries.push({ name, ...geometry, zoom, presentation })
  await writeFile(join(output, `${name}.png`), Buffer.from(await owner.evaluate(async win => (await win.webContents.capturePage()).toPNG().toString('base64')), 'base64'))
}
