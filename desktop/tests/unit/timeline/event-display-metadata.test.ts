test('omitted, undefined and empty display fields have intentional distinct serialization', () => {
  const absent = JSON.stringify(storyEventVersionPayload(payload()))
  assert.equal(JSON.stringify(storyEventVersionPayload({ ...payload(), content: { ...payload().content, title: undefined, rawCharacters: undefined } })), absent)
  const variants = [{ title: '' }, { rawCharacters: '' }, { title: '', rawCharacters: '' }]
  const hashes = variants.map(display => {
    const encoded = storyEventVersionPayload({ ...payload(), content: { ...payload().content, ...display } })
    for (const key of Object.keys(display)) assert.equal(encoded.content[key as keyof typeof display], '')
    return hash(JSON.stringify(encoded))
  })
  assert.equal(new Set([hash(absent), ...hashes]).size, 4)
})

