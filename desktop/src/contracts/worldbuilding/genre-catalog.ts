export function subgenresForGenre(genre: string): readonly SubgenreOption[] {
  return genreCatalog.find((item) => item.id === genre)?.subgenres ?? []
}

export function genreStrategy(genre: string, subgenre: string): string {
  const category = genreCatalog.find((item) => item.id === genre)
  if (!category) return '先明确题材承诺、核心冲突、人物成长与世界规则；任何扩写都不得改变已确认的因果与结局。'
  const detail = category.subgenres.find(([label]) => label === subgenre)
  return detail ? `${category.guidance}\n细分类策略：${detail[1]}` : category.guidance
}
