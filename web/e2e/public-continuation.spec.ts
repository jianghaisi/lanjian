import { test, expect, type Page } from '@playwright/test'


async function authenticate(page: Page, subject: string) {
  const start = await page.request.get('/api/auth/linuxdo/start', { maxRedirects: 0 })
  const callback = new URL(start.headers().location!); callback.searchParams.set('code', subject)
  await page.request.get(callback.href)
  const identity = await page.request.get('/api/me')
  expect(identity.status()).toBe(200)
  return (await identity.json()).user.id as string
}

test('existing animated login keeps real authorization, next destination and readiness states', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  const entry = page.getByRole('link', { name: '开始创作' })
  await expect(entry).toHaveAttribute('href', '/login')
  await entry.click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('button', { name: '使用 Linux DO 登录' })).toBeEnabled()
  await page.goto('/login?next=%2Fadmin&login=cancelled')
  await expect(page.locator('a[href="/app/reference"]')).toHaveCount(0)
  await expect(page.getByRole('link', { name: '返回项目介绍' })).toHaveAttribute('href', '/')
  await expect(page.locator('.mascot-eyes')).toBeVisible()
  await expect(page.locator('.ac-scene, .glass-backdrop')).toHaveCount(0)
  const body = page.locator('.mascot-gaze'), eyes = page.locator('.mascot-eye-look').first()
  await page.mouse.move(20, 300)
  const initial = await body.evaluate(el => getComputedStyle(el).transform)
  const initialEyes = await eyes.getAttribute('transform')
  await page.mouse.move(1350, 300)
  await expect.poll(() => body.evaluate(el => getComputedStyle(el).transform)).not.toBe(initial)
  await expect.poll(() => eyes.getAttribute('transform')).not.toBe(initialEyes)
  const eyelid = page.locator('.mascot-eyelid').first()
  const openHeight = (await eyelid.boundingBox())!.height
  await expect.poll(async () => (await eyelid.boundingBox())!.height, { timeout: 8500, intervals: [50] }).toBeLessThan(openHeight * .5)
  await expect(page.locator('.mascot-eyes')).toHaveAttribute('data-blinking', 'false')
  await expect(page.getByRole('status')).toContainText('你已取消授权')
  const loginButton = page.getByRole('button', { name: '使用 Linux DO 登录' })
  await loginButton.hover()
  await expect(page.getByTestId('login-mascot')).toHaveClass(/attentive/)
  await expect(eyes).toHaveAttribute('transform', 'translate(17 -10)')
  await expect.poll(() => page.locator('.mascot-body').evaluate(el => getComputedStyle(el).translate)).toBe('8px -20px')
  await expect(page).toHaveURL(/\/login\?next=/)
  await page.mouse.move(1380, 100)
  await expect(page.getByTestId('login-mascot')).not.toHaveClass(/attentive/)
  await expect(page.locator('input[type=password], iframe')).toHaveCount(0)
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'test-results/unified-login-desktop.png' })
  // This isolated server exchanges only synthetic identities; exercise the real library callback.
  const started = page.waitForResponse(response => new URL(response.url()).pathname === '/api/auth/linuxdo/start')
  await page.getByRole('button', { name: '使用 Linux DO 登录' }).click()
  expect((await started).status()).toBe(302)
  await expect(page).toHaveURL(/\/admin$/)
  await expect(page.getByText('此页面需要管理员权限。')).toBeVisible()
  const me = await (await page.request.get('/api/me')).json()
  const logout = await page.request.post('/api/auth/logout', { headers: { origin: 'http://127.0.0.1:5175', 'x-csrf-token': me.csrfToken } })
  expect(logout.ok()).toBe(true)
  await page.goto('/login')
  await page.route('**/api/site', route => route.fulfill({ json: { links: {}, welcomePoints: 10, loginConfigured: false } }))
  await page.reload(); await expect(page.getByRole('status')).toContainText('登录暂未开放')
  await expect(page.getByRole('button', { name: '使用 Linux DO 登录' })).toHaveCount(0)
  await page.unroute('**/api/site')
  await page.route('**/api/site', route => route.fulfill({ status: 503, json: { error: { code: 'configuration-required', message: '暂时无法读取站点' } } }))
  await page.reload(); await expect(page.getByRole('alert')).toContainText('暂时无法读取')
  await page.unroute('**/api/site')
  await page.getByRole('button', { name: '重新读取' }).click()
  await expect(page.getByRole('button', { name: '使用 Linux DO 登录' })).toBeEnabled()
  await page.getByRole('button', { name: '使用 Linux DO 登录' }).focus()
  await expect(page.getByTestId('login-mascot')).toHaveClass(/attentive/)
  for (const width of [768, 390, 320]) {
    await page.setViewportSize({ width, height: 844 }); await page.waitForTimeout(300)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/unified-login-${width}.png`, fullPage: true })
  }
  expect(errors).toEqual([])
})

