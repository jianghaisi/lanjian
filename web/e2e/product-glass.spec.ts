import { test, expect } from '@playwright/test'

test('product glass visibly grows, flows, pauses and restarts without covering tools', async ({page}) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  const stroke=page.locator('.glass-grow').first()
  await expect(page.getByRole('link',{name:'开始创作'})).toBeVisible()
  await page.getByRole('button',{name:'作品书库',exact:true}).click()
  const early=await stroke.evaluate(el=>Number.parseFloat(getComputedStyle(el).strokeDashoffset))
  await page.waitForTimeout(1200)
  const middle=await stroke.evaluate(el=>Number.parseFloat(getComputedStyle(el).strokeDashoffset))
  await page.screenshot({path:'test-results/product-glass-growing.png'})
  await page.waitForTimeout(2200)
  const late=await stroke.evaluate(el=>Number.parseFloat(getComputedStyle(el).strokeDashoffset))
  expect(early).toBeGreaterThan(middle); expect(middle).toBeGreaterThan(late); expect(late).toBeLessThan(1)
  const first=await page.locator('.product-material').screenshot()
  await page.waitForTimeout(450)
  const second=await page.locator('.product-material').screenshot()
  expect(first.equals(second)).toBe(false)
  await page.getByRole('button',{name:'暂停界面动效'}).click()
  await page.waitForTimeout(300)
  const pausedA=await page.locator('.product-material').screenshot()
  await page.waitForTimeout(450)
  const pausedB=await page.locator('.product-material').screenshot()
  expect(pausedA.equals(pausedB)).toBe(true)
  await page.getByRole('button',{name:'播放界面动效'}).click()
  await page.getByRole('button',{name:'正文编辑',exact:true}).click()
  expect(await stroke.evaluate(el=>Number.parseFloat(getComputedStyle(el).strokeDashoffset))).toBeGreaterThan(80)
  await page.waitForTimeout(3500)
  await page.screenshot({path:'test-results/product-glass-desktop.png'})
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'test-results/product-glass-mobile.png',fullPage:true})
  await page.emulateMedia({reducedMotion:'reduce'})
  expect(await stroke.evaluate(el=>getComputedStyle(el).strokeDashoffset)).toBe('0px')
  await expect(page.locator('.product-glass')).toHaveAttribute('aria-hidden','true')
  expect(errors).toEqual([])
})
