import { test, expect } from '@playwright/test'

test('hosted author creates a book without any model or API settings', async ({ page }) => {
  test.setTimeout(180000)
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  page.on('response', response => { if (response.status() >= 400) failures.push(`${response.status()} ${new URL(response.url()).pathname}`) })
  const start = await page.request.get('/api/auth/linuxdo/start', { maxRedirects: 0 })
  const url = new URL(start.headers().location!); url.searchParams.set('code', '855')
  await page.request.get(url.href)
  await page.goto('/app')
  await page.getByTestId('app-boot-enter').click({ timeout: 60000 })
  await expect(page.getByTestId('library-model-setup')).toHaveCount(0)
  await page.getByRole('button', { name: /新建空白作品/ }).first().click()
  await page.getByPlaceholder('例如：灯火照长安').fill('玻璃灯火')
  await expect(page.getByTestId('creation-model-defaults')).toHaveCount(0)
  await page.getByRole('button', { name: '创建空白作品', exact: true }).click()
  await expect(page.getByTestId('workspace-loading')).not.toBeVisible({ timeout: 60000 })
  await expect(page.getByTestId('group-chat-workspace')).toBeVisible()
  await page.getByRole('button', { name: '进入作品', exact: false }).click()
  await expect(page.locator('[data-activity="desk"]')).toBeVisible()
  const settings = await page.evaluate(() => window.novelDesktop!.ai.getSettings())
  expect(settings.modelConfigured).toBe(true)
  expect(settings.shared.model).toBe('fixture-model')
  expect(settings.connections).toHaveLength(1)
  await page.screenshot({ path: 'test-results/original-studio-new-book.png', animations: 'disabled' })
  expect(failures).toEqual([])
})

test('original AppShell opens a full reference copy and saves through the original editor', async ({ page }) => {
  test.setTimeout(180000)
  const failures: string[] = [], errors: string[] = []
  const consoleErrors: string[] = []
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(`${message.text()} ${message.location().url ?? ''}`) })
  page.on('response', response => { if (response.status() >= 400) failures.push(`${response.status()} ${new URL(response.url()).pathname}`) })
  page.on('pageerror', error => errors.push(error.message))
  const start = await page.request.get('/api/auth/linuxdo/start', { maxRedirects: 0 })
  const url = new URL(start.headers().location!); url.searchParams.set('code', '854')
  await page.request.get(url.href)
  const me = await (await page.request.get('/api/me')).json()
  const copied = await page.request.post('/api/reference-book/copy', { headers: { origin: 'http://127.0.0.1:5175', 'x-csrf-token': me.csrfToken }, data: {}, timeout: 60000 })
  expect(copied.ok()).toBeTruthy()
  await page.goto('/login')
  await expect(page).toHaveURL(/\/app$/)
  try {
    await page.getByTestId('app-boot-enter').click({ timeout: 60000 })
    await expect(page.getByTestId('app-boot')).not.toBeVisible()
    await expect(page.getByRole('button', { name: /打开作品.*渡口最后一盏灯|继续创作/ }).first()).toBeVisible()
    const companion = page.locator('.library-companion-stage .live2d-companion')
    await expect(companion).toHaveAttribute('data-ready', 'true')
    await expect(companion.locator('canvas')).toBeVisible()
    const character = page.getByTestId('interactive-archive-character')
    const action = Number(await character.getAttribute('data-action'))
    await page.getByTestId('archive-character-talk').click()
    await expect(character).toHaveAttribute('data-action', String(action + 1))
    await page.screenshot({ path: 'test-results/original-studio-library.png', animations: 'disabled' })
    await page.getByRole('button', { name: /打开作品.*渡口最后一盏灯|继续创作/ }).first().click()
    await expect(page.locator('[data-activity="desk"]')).toBeVisible()
    await expect(page.getByTestId('workspace-loading')).not.toBeVisible()
    await page.getByTestId('desktop-companion-notice').click()
    await expect(page.getByRole('status').filter({ hasText: '独立桌宠需下载完整版体验。' })).toBeVisible()
    await expect(page).toHaveURL(/\/app$/)
    await expect(page.getByTestId('desktop-pet-tools-toggle')).toHaveCount(0)
    await page.locator('[data-activity="desk"]').click()
    const editor = page.getByTestId('manuscript-input')
    await expect(editor).toBeVisible()
    await expect(page.getByRole('textbox', { name: '章节标题', exact: true })).toHaveValue('天亮后点灯')
    await page.getByRole('button', { name: /^第 1 章，/ }).click()
    await expect(page.getByRole('textbox', { name: '章节标题', exact: true })).toHaveValue('少了一页的账')
    await expect(editor).toContainText('沈禾')
    await editor.fill('浏览器沿用原版编辑器。灯还亮着。')
    await page.getByRole('button', { name: '立即保存', exact: true }).click()
    await expect.poll(() => page.evaluate(async () => (await window.novelDesktop!.chapters.get(1)).content)).toContain('灯还亮着。')
    await page.screenshot({ path: 'test-results/original-studio-editor.png', animations: 'disabled' })
    expect(failures).toEqual([]); expect(errors).toEqual([]); expect(consoleErrors).toEqual([])
  } finally {
    await test.info().attach('original-studio-diagnostics', { body: JSON.stringify({ failures, errors, consoleErrors, text: await page.locator('body').innerText() }, null, 2), contentType: 'application/json' })
  }
})
