import { test, expect } from '@playwright/test'

test('real browser login, private library, Chinese save, recovery, task, credits, import and export', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  const requests: string[] = []; page.on('request', r => requests.push(r.url()))
  await page.goto('/app')
  await page.getByRole('link', { name: '使用 Linux DO 登录' }).click()
  await expect(page.getByRole('heading', { name: '我的作品' })).toBeVisible()
  await expect(page.getByLabel('查看积分明细')).toContainText('10 积分')
  await page.getByLabel('新作品名称').fill('浏览器验收样书')
  await page.getByRole('button', { name: '＋ 新建作品', exact: true }).click()
  await page.getByRole('button', { name: '＋ 新章', exact: true }).click()
  const editor = page.getByRole('textbox', { name: '正文内容', exact: true })
  await expect(editor).toBeVisible()
  await page.getByLabel('章节标题').fill('旧城来信')
  await editor.fill('林舟推开旧城的门，雨声落在石阶上。')
  await page.getByRole('button', { name: '保存正文', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '正文已保存' })).toBeVisible()
  await editor.fill('林舟推开旧城的门，雨声落在石阶上。这是尚未保存的下一句。')
  await page.getByRole('button', { name: '← 我的作品' }).click()
  await page.getByRole('button').filter({ hasText: '浏览器验收样书' }).click()
  await expect(page.getByText('发现未保存的草稿')).toBeVisible()
  await page.getByRole('button', { name: '恢复到编辑器' }).click()
  await expect(editor).toContainText('尚未保存的下一句')
  await page.getByRole('button', { name: '保存正文', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '正文已保存' })).toBeVisible()
  await editor.focus(); await page.keyboard.press('Control+Home'); await page.keyboard.press('Control+Shift+ArrowRight')
  await page.getByText('正文批注（0）', { exact: true }).click()
  await page.getByLabel('批注意见').fill('下一稿补充门前的声音。'); await page.getByRole('button', { name: '保存批注', exact: true }).click()
  await expect(page.getByText('下一稿补充门前的声音。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '标为已解决' }).click(); await expect(page.getByRole('button', { name: '重新打开' })).toBeVisible()
  await page.getByLabel('写作任务').selectOption('query')
  await page.getByLabel('你的要求').fill('讨论本章雨夜的描写')
  await page.getByRole('button', { name: '开始任务', exact: true }).click()
  await expect(page.getByText('候选已完成', { exact: true })).toBeVisible({ timeout: 60000 })
  await expect(page.getByLabel('查看积分明细')).toContainText('9 积分')
  await page.getByLabel('查看积分明细').click()
  await expect(page.getByRole('dialog', { name: '积分明细' })).toContainText('首次登录赠送')
  await page.getByRole('dialog', { name: '积分明细' }).getByRole('button', { name: '关闭' }).click()
  await page.getByRole('button', { name: '导入稿件', exact: true }).click()
  await page.getByLabel('选择文件').setInputFiles({ name: '补充.txt', mimeType: 'text/plain', buffer: Buffer.from('第一章 外来者\n他带来一封信。\n第二章 灯火\n灯光照亮了来客。', 'utf8') })
  await expect(page.getByRole('dialog', { name: '导入作品' })).toContainText('2 章')
  await page.getByRole('button', { name: '确认导入所选内容' }).click()
  await expect(page.getByRole('dialog', { name: '导入作品' })).not.toBeVisible()
  const downloading = page.waitForEvent('download'); await page.getByRole('link', { name: '导出 Markdown' }).click(); expect((await downloading).suggestedFilename()).toMatch(/\.md$/)
  await page.screenshot({ path: 'test-results/experience-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: 'test-results/experience-mobile.png', fullPage: true })
  expect(requests.filter(url => new URL(url).pathname.startsWith('/api/') && /local-model|voice|speech|electron/.test(url))).toEqual([])
  expect(await page.content()).not.toContain('synthetic-model-secret')
  expect(errors).toEqual([])
})

test('author completes definitions, event adoption, confirmed hierarchy and reviewed prose in browser', async ({ page }) => {
  await page.goto('/app'); await page.getByRole('link', { name: '使用 Linux DO 登录' }).click()
  await page.getByLabel('新作品名称').fill('完整创作流程样书'); await page.getByRole('button', { name: '＋ 新建作品', exact: true }).click()
  await page.getByRole('button', { name: '＋ 新章', exact: true }).click()
  await expect(page.getByLabel('章节标题')).toBeVisible()
  const module = (name: string) => page.getByRole('navigation', { name: '作品模块' }).getByRole('button', { name: new RegExp(name) })
  await module('定书').click()
  await page.getByLabel('核心设想').fill('林舟因为收到旧信而调查，于是发现名字矛盾，最终找出真相。')
  await page.getByLabel('小说题材').fill('悬疑'); await page.getByLabel('每章目标字数').fill('1000')
  await page.getByRole('button', { name: '保存设定', exact: true }).first().click()
  await expect(page.getByRole('status')).toContainText('已保存到当前作品')
  // A second save must use the newly acknowledged core profile revision.
  await page.getByLabel('写作风格').fill('细致、克制'); await page.getByRole('button', { name: '保存设定', exact: true }).first().click()
  await expect(page.getByRole('status')).toContainText('已保存到当前作品')
  await module('设定').click()
  await page.getByLabel('世界观', { exact: true }).fill('旧城只有人力，没有超自然力量。')
  await page.getByLabel('启用境界 / 实力表').check(); await page.getByRole('button', { name: '＋ 添加境界' }).click()
  await page.getByLabel('境界名称').fill('观微境'); await page.getByLabel('能力与限制').fill('只能辨认纸面痕迹，不能隔空探查。')
  await page.getByLabel('启用固定系统界面模板').check(); await page.getByLabel('系统界面模板', { exact: true }).fill('[线索面板]\n[属性]\n[技能]\n[任务]')
  await page.getByRole('button', { name: '保存设定', exact: true }).first().click(); await expect(page.getByRole('status')).toContainText('已保存到当前作品')
  await module('纪事').click()
  await page.getByLabel('时间', { exact: true }).fill('第一日午后'); await page.getByLabel('人物', { exact: true }).fill('林舟'); await page.getByLabel('地点', { exact: true }).fill('旧城')
  await page.getByLabel('发生了什么').fill('核对旧信的落款'); await page.getByLabel('结果与影响').fill('发现名字不符')
  await page.getByRole('button', { name: '预览并保存事件' }).click(); await page.getByRole('dialog', { name: '确认事件' }).getByRole('button', { name: '确认', exact: true }).click()
  // Author-created events become formal only after the explicit preview confirmation.
  await expect(page.getByText('计划发生', { exact: true })).toBeVisible()
  await module('谋篇').click()
  await page.getByLabel('新增分卷').fill('旧城'); await page.getByRole('button', { name: '创建分卷', exact: true }).click()
  await expect(page.getByLabel('当前文档').locator('option[value="volume:1"]')).toHaveCount(1)
  const outline = page.getByRole('textbox', { name: '大纲正文', exact: true })
  async function saveConfirm(scope: string, text: string) {
    await page.getByLabel('当前文档').selectOption(scope); await expect(outline).toBeEditable(); await outline.fill(text)
    await page.getByRole('button', { name: '保存大纲', exact: true }).click(); await expect(page.getByRole('status')).toContainText('已保存。')
    const acknowledge = page.getByRole('button', { name: '已核对以上提示' }); if (await acknowledge.isVisible()) await acknowledge.click()
    await page.getByRole('button', { name: '确认当前大纲', exact: true }).click(); await expect(page.getByRole('status')).toContainText('当前大纲已确认')
  }
  await saveConfirm('total', '林舟因为收到旧信而调查，于是发现名字矛盾，最终找出真相。')
  await saveConfirm('volume:1', '林舟进入旧城，因为发现落款不符而查找证人，最终找到发信人。')
  await page.getByLabel('当前文档').selectOption('chapter:1'); await expect(outline).toBeEditable()
  await page.getByRole('button', { name: '设置分卷' }).click(); await expect(page.getByRole('status')).toContainText('归属已更新')
  await page.getByLabel('分配正式事件').selectOption({ label: '核对旧信的落款' }); await page.getByRole('button', { name: '关联到本章' }).click()
  await saveConfirm('chapter:1', '进入状态：林舟拿着旧信，尚未核对落款\n1. 核对旧信的落款\n2. 发现名字不符\n退出状态：林舟决定寻找证人，尚未离开旧城\n允许扩写：纸面细节；动作；环境；对白\n禁止：不得提前找到发信人')
  await module('正文').click(); await page.getByLabel('写作任务').selectOption('continue'); await page.getByRole('button', { name: '开始任务', exact: true }).click()
  await expect(page.getByText('候选已完成', { exact: true })).toBeVisible({ timeout: 60000 })
  const prose = page.getByRole('textbox', { name: '正文内容', exact: true }); await expect(page.locator('.editor-status')).toContainText('0 字符')
  await expect(page.getByText('审校通过', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '采用到当前正文' }).click(); await expect(prose).toContainText('决定前去寻找证人')
  await page.screenshot({ path: 'test-results/reviewed-writing.png', fullPage: true })
})
