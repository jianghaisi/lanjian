  test.setTimeout(180000)
  await page.goto('/app/reference')
  await enter(page)
  await expect(page).toHaveURL(/\/app\?guest=1/)
  await page.getByRole('button', { name: /第 5 章，天亮后点灯/ }).click()
  await page.locator('.cm-content').focus(); await page.keyboard.press('End')
