import { test, expect, type Page } from '@playwright/test'

async function enter(page: Page) {
  const direct = page.getByRole('button', { name: /直接进入/ })
  await expect(page.getByTestId('app-boot-enter').or(direct).or(page.getByLabel('章节标题'))).not.toHaveCount(0, { timeout: 60000 })
  if (await direct.isVisible()) await direct.click()
  else if (await page.getByTestId('app-boot-enter').isVisible()) await page.getByTestId('app-boot-enter').click()
  await expect(page.getByLabel('章节标题')).toBeVisible({ timeout: 60000 })
  await expect(page.getByTestId('workspace-loading')).not.toBeVisible({ timeout: 60000 })
}

