  await page.locator('[data-nav-parent="foundation"]').click()
  await page.locator('[data-nav-leaf="system-template"]').click()
  await expect(page.getByTestId('system-ui-config-page')).toBeVisible()
  await page.locator('[data-nav-parent="manuscript"]').click()
