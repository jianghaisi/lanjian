  await page.getByRole('button', { name: '打开智能助笔侧栏', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '智能助笔', exact: true })).toBeVisible()
  await expect(page.getByTestId('assistant-mode-agent')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '打开智能助笔侧栏', exact: true })).toBeFocused()
