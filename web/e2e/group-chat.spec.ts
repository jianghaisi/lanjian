import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'

test('group tab creates a real book with independent member models and reviewed adoption', async ({ page }) => {
  test.setTimeout(180000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const output = resolve('../.trellis/tasks/10-11-v3-group-chat-assistant-ui/research/browser')
  await mkdir(output, { recursive: true })
  const start = await page.request.get('/api/auth/linuxdo/start', { maxRedirects: 0 })
  const login = new URL(start.headers().location!); login.searchParams.set('code', '856')
  await page.request.get(login.href)
  await page.addInitScript(() => localStorage.setItem('lanjian-loading-v1', JSON.stringify({ theme: 'impact', bootStyle: 'brief', bootPalette: 'system' })))
  await page.goto('/app')
  await page.getByTestId('app-boot-enter').click({ timeout: 60000 })
  await expect(page.getByTestId('group-chat-tab')).toHaveCount(0)
  await page.getByRole('button', { name: /新建空白作品/ }).click()
  await page.getByPlaceholder('例如：灯火照长安').fill('浏览器雨夜修复师')
  await page.getByTestId('create-book-genre').fill('都市奇幻')
  await page.getByRole('button', { name: '创建空白作品', exact: true }).click()
  await expect(page.getByTestId('group-chat-workspace')).toBeVisible({ timeout: 60000 })
  await expect.poll(() => page.evaluate(async () => (await window.novelDesktop!.workspace.getBookProfile()).genre)).toBe('都市奇幻')
  await expect(page.locator('.group-thread-header h1')).toHaveText('浏览器雨夜修复师')
  await expect(page.locator('[data-nav-parent=group]')).toHaveAttribute('aria-current', 'step')
  await expect(page.locator('[data-nav-parent=group] svg path').first()).toBeVisible()
  expect(await page.locator('.activitybar').evaluate(el => el.clientHeight)).toBeGreaterThan(400)
  expect(await page.locator('[data-nav-parent=definition]').evaluate(el => { const r = el.getBoundingClientRect(); return el.contains(document.elementFromPoint(r.left + 20, r.top + r.height / 2)) })).toBe(true)
  expect(await page.locator('.group-send').evaluate(el => parseFloat(getComputedStyle(el).borderTopLeftRadius))).toBeGreaterThanOrEqual(8)
  await expect(page.getByTestId('book-tabs').getByTestId('group-chat-tab')).toHaveCount(0)
  await expect(page.locator('[data-book-tab][aria-current=page]')).toHaveCount(1)
  await page.getByRole('button', { name: '世界观设定师成员设置' }).click()
  const settings = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '世界观设定师' }) })
  await settings.locator('.model-catalog-trigger').click()
  await page.locator('.model-choice-list button[data-model="world-fixture-model"]').click()
  await settings.getByRole('button', { name: '保存成员设置' }).click()
  await expect(settings).not.toBeVisible()
  const composer = page.getByRole('textbox', { name: '给创作团队的消息' })
  await composer.fill('我想写关于雨夜旧物修复师的都市奇幻，请整理这本书的设定与故事方向。')
  await composer.press('Control+Enter')
  await expect(page.locator('.group-result-card').filter({ hasText: '记忆与代价' })).toBeVisible({ timeout: 60000 })
  await expect(page.locator('.group-message.agent').filter({ hasText: 'fixture-model' }).first()).toBeVisible()
  await expect(page.locator('.group-message.agent').filter({ hasText: 'world-fixture-model' })).toBeVisible()
  await page.screenshot({ path: resolve(output, '01-preparation.png'), animations: 'disabled' })
  const world = page.locator('.group-result-card').filter({ hasText: '记忆与代价' })
  await world.locator('summary').click()
  await world.getByRole('button', { name: '核对并采用' }).click()
  const adoption = page.getByRole('dialog', { name: '核对筹备采用' })
  await expect(adoption).toBeVisible()
  const before = await page.evaluate(async () => (await window.novelDesktop!.workspace.getFoundation()).worldView)
  expect(before).toBe('')
  await adoption.getByRole('button', { name: '确认采用到世界设定 · 世界观' }).click()
  await expect(adoption).not.toBeVisible()
  await expect.poll(() => page.evaluate(async () => (await window.novelDesktop!.workspace.getFoundation()).worldView)).toBe('旧物记录记忆，每次修复必须舍弃一段往事。')
  const normalModels = await page.evaluate(() => window.novelDesktop!.ai.getSettings())
  expect(normalModels.shared.model).toBe('fixture-model')
  await composer.fill('保留在群聊中的草稿')
  await page.locator('[data-nav-parent=definition]').click()
  await expect(page.locator('.studio')).toHaveAttribute('data-page', 'profile')
  const assistant = page.getByTestId('assistant-sidebar')
  if (!await assistant.isVisible()) await page.getByRole('button', { name: '打开智能助笔侧栏', exact: true }).click()
  await expect(assistant).toBeVisible()
  const assistantDraft = page.getByTestId('field-assistant-instruction')
  await assistantDraft.fill('原助笔输入在群聊往返后保留')
  await page.getByTestId('group-chat-tab').click()
  await expect(composer).toHaveValue('保留在群聊中的草稿')
  await expect(assistant).toBeHidden()
  await expect(page.locator('.studio')).toHaveAttribute('data-assistant-open', 'false')
  expect(await page.locator('.activitybar').evaluate(el => el.clientHeight)).toBeGreaterThan(400)
  await page.locator('[data-nav-parent=definition]').click()
  await expect(assistant).toBeVisible()
  await expect(assistantDraft).toHaveValue('原助笔输入在群聊往返后保留')
  await page.getByTestId('group-chat-tab').click()
  await expect(assistant).toBeHidden()
  await page.screenshot({ path: resolve(output, '02-bound.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: '展开会话与成员' })).toBeVisible()
  await page.getByRole('button', { name: '展开会话与成员' }).click()
  await expect(page.getByRole('button', { name: '世界观设定师成员设置' })).toBeVisible()
  await page.locator('.group-mobile-backdrop').click({ position: { x: 280, y: 300 } })
  await page.getByRole('button', { name: '查看筹备成果' }).click()
  await expect(world).toBeVisible()
  await page.screenshot({ path: resolve(output, '03-mobile-results.png'), animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '关闭成果', exact: true }).click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await page.locator('.group-message').first().evaluate(el => getComputedStyle(el).animationName)).toBe('none')
  await page.reload()
  await page.getByTestId('app-boot-enter').click({ timeout: 60000 })
  await page.getByRole('button', { name: /打开作品.*浏览器雨夜修复师|继续创作/ }).first().click()
  await page.getByTestId('group-chat-tab').click()
  await expect(composer).toHaveValue('保留在群聊中的草稿')
  expect(errors).toEqual([])
})
